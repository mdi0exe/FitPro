#!/usr/bin/env node
/**
 * dump-code.mjs — concatenate the whole hand-written codebase into a single
 * text file (project-code-dump.txt) for handing to an LLM.
 *
 * Faithful successor to the old `python bundle_code.py` that produced the
 * same artefact. Auto-discovers files so newly added sources are always
 * included; excludes generated output, dependencies, build dirs and binaries
 * (notably the committed PKCS12 keystore and the generated exercise catalog).
 *
 * Usage: node scripts/dump-code.mjs        (writes ../project-code-dump.txt)
 *        node scripts/dump-code.mjs --out custom.txt
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// ---- include / exclude policy -------------------------------------------

const INCLUDE_EXT = new Set([
  ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs",
  ".rs", ".toml", ".json", ".yml", ".yaml",
  ".html", ".css", ".svg", ".md", ".conf", ".lock",
]);
const BINARY_EXT = new Set([
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", // images
  ".mp3", ".wav", ".ogg", ".m4a", ".aac",            // audio
  ".woff", ".woff2", ".ttf", ".otf",                 // fonts
  ".keystore", ".jks", ".p12", ".pfx", ".bin",       // keys / blobs
  ".zip", ".apk", ".ipa",                             // packages
]);
const EXCLUDE_DIRS = new Set([
  "node_modules", "dist", ".git", "target", "gen",
  ".tmp", "shots", "public", "coverage", ".workbuddy-ai",
  ".vscode", "__pycache__", ".idea", "android", "ios",
]);
// Files explicitly skipped even if their extension matches.
const EXCLUDE_FILES = new Set([
  "package-lock.json", "yarn.lock", "pnpm-lock.yaml",
  "src/data/exerciseCatalog.ts", // generated by scripts/build-exercise-library.mjs
]);

function isBinaryExt(p) {
  return BINARY_EXT.has(path.extname(p).toLowerCase());
}
function inExcludedDir(rel) {
  // rel is normalised to "/" separators (see collect()), so split on "/".
  return rel.split("/").some((seg) => EXCLUDE_DIRS.has(seg));
}

/** Collect every file we want to dump, keyed by posix-relative path. */
function collect() {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      const rel = path.relative(ROOT, abs).split(path.sep).join("/");
      if (entry.isDirectory()) {
        if (inExcludedDir(rel)) continue;
        walk(abs);
        continue;
      }
      // Inside src-tauri/icons only the vector source matters; the generated
      // PNG/ICNS mipmaps are binaries.
      if (rel.startsWith("src-tauri/icons/") && path.extname(rel).toLowerCase() !== ".svg") continue;
      if (inExcludedDir(rel)) continue;
      if (EXCLUDE_FILES.has(rel)) continue;
      if (isBinaryExt(rel)) continue;
      const ext = path.extname(rel).toLowerCase();
      if (!INCLUDE_EXT.has(ext)) continue;
      out.push(rel);
    }
  };
  walk(ROOT);
  return out;
}

// ---- ordering ------------------------------------------------------------

function rank(rel) {
  if (rel === "README.md") return 0;
  if (rel === "package.json") return 1;
  if (rel.startsWith(".github/")) return 2;
  if (rel.startsWith("scripts/")) return 3;
  if (rel.startsWith("src-tauri/")) return 4;
  if (rel.startsWith("src/")) return 5;
  return 6;
}
function order(files) {
  return files.sort((a, b) => {
    const r = rank(a) - rank(b);
    if (r !== 0) return r;
    return a.localeCompare(b);
  });
}

// ---- directory tree (included files only) -------------------------------

function buildTree(rels) {
  const root = { dirs: new Map(), files: new Set() };
  for (const rel of rels) {
    const parts = rel.split("/");
    let node = root;
    for (let i = 0; i < parts.length - 1; i++) {
      const seg = parts[i];
      if (!node.dirs.has(seg)) node.dirs.set(seg, { dirs: new Map(), files: new Set() });
      node = node.dirs.get(seg);
    }
    node.files.add(parts[parts.length - 1]);
  }
  const lines = [];
  const render = (node, prefix) => {
    const dirNames = [...node.dirs.keys()].sort();
    const fileNames = [...node.files].sort();
    const all = [
      ...dirNames.map((d) => [d, true]),
      ...fileNames.map((f) => [f, false]),
    ];
    all.forEach(([name, isDir], idx) => {
      const last = idx === all.length - 1;
      lines.push(prefix + (last ? "└── " : "├── ") + name + (isDir ? "/" : ""));
      if (isDir) render(node.dirs.get(name), prefix + (last ? "    " : "│   "));
    });
  };
  render(root, "");
  return lines;
}

// ---- language tag --------------------------------------------------------

function langOf(rel) {
  switch (path.extname(rel).toLowerCase()) {
    case ".ts": case ".tsx": return "typescript";
    case ".js": case ".jsx": case ".mjs": case ".cjs": return "javascript";
    case ".rs": return "rust";
    case ".toml": return "toml";
    case ".json": return "json";
    case ".yml": case ".yaml": return "yaml";
    case ".html": return "html";
    case ".css": return "css";
    case ".svg": return "xml";
    case ".md": return "markdown";
    default: return "text";
  }
}

// ---- git revision --------------------------------------------------------

function revision() {
  try {
    const sha = execSync("git rev-parse --short HEAD", { cwd: ROOT }).toString().trim();
    const status = execSync("git status --porcelain", { cwd: ROOT }).toString().trim();
    const branch = execSync("git rev-parse --abbrev-ref HEAD", { cwd: ROOT }).toString().trim();
    const subject = execSync("git log -1 --pretty=%s", { cwd: ROOT }).toString().trim();
    return `${branch} @ ${sha} ${status ? "(dirty)" : "(clean)"} — ${subject}`;
  } catch {
    return "unknown";
  }
}

// ---- main ----------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  const outIdx = args.indexOf("--out");
  const outPath = outIdx >= 0 ? args[outIdx + 1] : path.join(ROOT, "project-code-dump.txt");

  const files = order(collect());
  const tree = buildTree(files);

  let totalLines = 0;
  let totalBytes = 0;
  const contents = files.map((rel) => {
    const abs = path.join(ROOT, rel);
    const buf = fs.readFileSync(abs);
    const text = buf.toString("utf8");
    const lines = text.replace(/\r\n/g, "\n").split("\n").length;
    const bytes = buf.length;
    totalLines += lines;
    totalBytes += bytes;
    return { rel, text, lines, bytes };
  });

  const created = new Date().toISOString().slice(0, 16).replace("T", " ");
  const tokens = Math.round(totalBytes / 4);

  const wrap = (label) => `==============================================================================`;
  const header = [
    wrap(),
    " PROJECT CODE DUMP",
    ` Project : APK`,
    ` Root    : ${ROOT}`,
    ` Created : ${created}`,
    ` Revision: ${revision()}`,
    ` Files   : ${files.length}    Lines: ${totalLines.toLocaleString("en-US")}    Size: ${(totalBytes / 1024).toFixed(1)} KB`,
    ` Tokens  : ~${tokens.toLocaleString("en-US")} (rough estimate, chars / 4)`,
    wrap(),
    "",
    " HOW TO READ THIS FILE",
    " ---------------------",
    " Every file below is introduced by a header line with its relative path",
    " and line count, followed by a language-tagged fenced code block.",
    " Files are ordered: README/manifests first, then alphabetically by area.",
    " Generated output, dependencies and binaries were excluded.",
    "",
    " PROJECT AT A GLANCE",
    " -------------------",
    " Tauri v2 (Android + Desktop) fitness tracker for Persian-speaking students.",
    " Backend: Rust (src-tauri/src) — models, atomic JSON storage, IPC commands.",
    " Frontend: Vite + TypeScript + Tailwind, 100% Persian RTL UI (src/).",
    " CI: GitHub Actions (.github/workflows) builds a debug Android APK signed",
    "     with a committed PKCS12 keystore (src-tauri/keystore) so APK updates",
    "     install over the previous one without wiping gym_state.json.",
    " Assets: public/sounds and public/gifs are bundled offline (binaries,",
    "     excluded from this dump).",
    " Key feature areas: workout/plate logic (src/lib/workoutTools.ts),",
    "     university schedule + shuttle (src/views/uni*.ts), nutrition/coach",
    "     (src/views/nutrition.ts, src/views/coach.ts), AI diet configurator",
    "     (src/components/aiDietConfigurator.ts), per-exercise history +",
    "     double-progression (src/components/exerciseHistory.ts,",
    "     src/components/doubleProgression.ts), and the generated 120-movement",
    "     exercise catalog (scripts/build-exercise-library.mjs →",
    "     src/data/exerciseCatalog.ts, excluded as generated).",
    "",
    " DIRECTORY TREE (included files only)",
    " ------------------------------------",
    ...tree.map((l) => " " + l),
    "",
    " TABLE OF CONTENTS",
    " -----------------",
    ...contents.map((c, i) => {
      const label = `${i + 1}. ${c.rel}`;
      const dots = ".".repeat(Math.max(3, 42 - label.length));
      return `  ${label}${dots} ${c.lines} lines`;
    }),
    "",
  ];

  const blocks = contents.map((c, i) => {
    const kb = (c.bytes / 1024).toFixed(1);
    return [
      wrap(),
      ` FILE ${i + 1}/${files.length}: ${c.rel}`,
      ` ${c.lines} lines · ${kb} KB`,
      wrap(),
      "```" + langOf(c.rel),
      c.text.replace(/\s+$/, ""),
      "```",
      "",
    ].join("\n");
  });

  const footer = [
    wrap(),
    " END OF DUMP",
    wrap(),
    "",
  ].join("\n");

  const out = [...header, ...blocks, footer].join("\n");
  fs.writeFileSync(outPath, out, "utf8");

  console.log(`Wrote ${path.relative(ROOT, outPath)}`);
  console.log(`  files : ${files.length}`);
  console.log(`  lines : ${totalLines.toLocaleString("en-US")}`);
  console.log(`  size  : ${(totalBytes / 1024).toFixed(1)} KB`);
  console.log(`  tokens: ~${tokens.toLocaleString("en-US")}`);
  console.log("  areas :");
  console.log(`    scripts/      ${files.filter((f) => f.startsWith("scripts/")).length}`);
  console.log(`    src/          ${files.filter((f) => f.startsWith("src/")).length}`);
  console.log(`    src-tauri/    ${files.filter((f) => f.startsWith("src-tauri/")).length}`);
  console.log(`    .github/      ${files.filter((f) => f.startsWith(".github/")).length}`);
}

main();
